const BASE_STATIC_TIME = 1730030400000;

export function generateHistoricalSensorData(
  baseEquipment: Equipment,
  baseEpochMs = BASE_STATIC_TIME
): SensorDataPoint[] {
  const points: SensorDataPoint[] = [];
  const now = baseEpochMs;
  const count = 30; // 30 time points (e.g. last 60 seconds)

  for (let i = count - 1; i >= 0; i--) {
    const timestampMs = now - i * 2000;
    const date = new Date(timestampMs);
    const mm = String(date.getUTCMinutes()).padStart(2, "0");
    const ss = String(date.getUTCSeconds()).padStart(2, "0");
    const timeFormatted = `${mm}:${ss}`;

    // Seeded sine waves + deterministic pseudo-harmonic variation for realistic industrial readings
    const sineFactor = Math.sin((count - i) * 0.45);
    const cosFactor = Math.cos((count - i) * 0.3);
    const pseudoNoise = (((i * 17) % 11) - 5) * 0.03;

    let vib = baseEquipment.vibration + sineFactor * 0.4 + pseudoNoise;
    let temp = baseEquipment.temperature + cosFactor * 0.8 + pseudoNoise * 1.5;
    let press = baseEquipment.pressure + sineFactor * 2.5 + pseudoNoise * 4.0;
    let rpm = baseEquipment.rpm + Math.round(sineFactor * 40 + (((i * 23) % 13) - 6) * 2);

    // Keep non-negative
    vib = Math.max(0.1, Number(vib.toFixed(2)));
    temp = Math.max(10, Number(temp.toFixed(1)));
    press = Math.max(10, Number(press.toFixed(1)));

    points.push({
      timestamp: new Date(timestampMs).toISOString(),
      timeFormatted,
      vibration: vib,
      temperature: temp,
      pressure: press,
      rpm,
      vibrationThresholdWarning: 3.5,
      vibrationThresholdCritical: 5.5,
      tempThresholdWarning: 75.0,
      tempThresholdCritical: 85.0,
      pressureThresholdWarning: 155.0,
      pressureThresholdCritical: 180.0,
    });
  }

  return points;
}

